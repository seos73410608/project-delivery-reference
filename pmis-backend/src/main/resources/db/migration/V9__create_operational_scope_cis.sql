
CREATE TABLE public.operational_scope_cis (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    operational_scope_id BIGINT NOT NULL,
    ci_id BIGINT NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE,

    CONSTRAINT pk_operational_scope_cis
        PRIMARY KEY (id),

    CONSTRAINT uk_operational_scope_cis_scope_ci
        UNIQUE (operational_scope_id, ci_id),

    CONSTRAINT fk_operational_scope_cis_scope
        FOREIGN KEY (operational_scope_id)
        REFERENCES public.operational_scopes (id)
        ON DELETE CASCADE,

    CONSTRAINT fk_operational_scope_cis_ci
        FOREIGN KEY (ci_id)
        REFERENCES public.configuration_items (id)
        ON DELETE CASCADE
);

CREATE INDEX idx_operational_scope_cis_scope_id
    ON public.operational_scope_cis (operational_scope_id);

CREATE INDEX idx_operational_scope_cis_ci_id
    ON public.operational_scope_cis (ci_id);
