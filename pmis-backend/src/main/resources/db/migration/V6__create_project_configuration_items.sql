CREATE TABLE public.project_configuration_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    project_id BIGINT NOT NULL,
    ci_id BIGINT NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,

    CONSTRAINT pk_project_configuration_items
        PRIMARY KEY (id),

    CONSTRAINT uk_project_configuration_items_project_ci
        UNIQUE (project_id, ci_id),

    CONSTRAINT fk_project_configuration_items_project
        FOREIGN KEY (project_id)
        REFERENCES public.projects (id)
        ON DELETE CASCADE,

    CONSTRAINT fk_project_configuration_items_ci
        FOREIGN KEY (ci_id)
        REFERENCES public.configuration_items (id)
        ON DELETE CASCADE
);

CREATE INDEX idx_project_configuration_items_project_id
    ON public.project_configuration_items (project_id);

CREATE INDEX idx_project_configuration_items_ci_id
    ON public.project_configuration_items (ci_id);

