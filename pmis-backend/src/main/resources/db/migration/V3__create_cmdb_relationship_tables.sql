-- ============================================================================
-- V3: CMDB Relationship
-- PostgreSQL
--
-- Tables:
--   1. ci_relationship_types
--   2. ci_relationships
--
-- Policy:
--   1. Directed relationship
--   2. One relationship per source, target and type
--   3. Inactive relationship is reactivated instead of recreated
--   4. Self relationship is prohibited
-- ============================================================================


-- ============================================================================
-- 1. CI Relationship Types
-- ============================================================================

CREATE TABLE public.ci_relationship_types
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    created_at  TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITHOUT TIME ZONE,

    code        VARCHAR(50) NOT NULL,
    name        VARCHAR(100) NOT NULL,
    description VARCHAR(500),

    enabled     BOOLEAN NOT NULL DEFAULT TRUE,
    sort_order  INTEGER NOT NULL DEFAULT 0,

    CONSTRAINT pk_ci_relationship_types
        PRIMARY KEY (id),

    CONSTRAINT uk_ci_relationship_types_code
        UNIQUE (code)
);


-- ============================================================================
-- 2. CI Relationships
-- ============================================================================

CREATE TABLE public.ci_relationships
(
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    created_at              TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at              TIMESTAMP WITHOUT TIME ZONE,

    source_ci_id            BIGINT NOT NULL,
    target_ci_id            BIGINT NOT NULL,
    relationship_type_id    BIGINT NOT NULL,

    description             VARCHAR(1000),

    status                  VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',

    deactivated_at          TIMESTAMP WITHOUT TIME ZONE,
    deactivated_by          BIGINT,
    deactivation_reason     VARCHAR(500),

    CONSTRAINT pk_ci_relationships
        PRIMARY KEY (id),

    CONSTRAINT uk_ci_relationships_source_target_type
        UNIQUE (source_ci_id, target_ci_id, relationship_type_id),

    CONSTRAINT ck_ci_relationships_no_self_reference
        CHECK (source_ci_id <> target_ci_id),

    CONSTRAINT ck_ci_relationships_status
        CHECK (status IN ('ACTIVE', 'INACTIVE')),

    CONSTRAINT ck_ci_relationships_deactivation
        CHECK (
            (
                status = 'ACTIVE'
                AND deactivated_at IS NULL
                AND deactivated_by IS NULL
                AND deactivation_reason IS NULL
            )
            OR
            (
                status = 'INACTIVE'
                AND deactivated_at IS NOT NULL
            )
        ),

    CONSTRAINT fk_ci_relationships_source_ci
        FOREIGN KEY (source_ci_id)
        REFERENCES public.configuration_items (id),

    CONSTRAINT fk_ci_relationships_target_ci
        FOREIGN KEY (target_ci_id)
        REFERENCES public.configuration_items (id),

    CONSTRAINT fk_ci_relationships_type
        FOREIGN KEY (relationship_type_id)
        REFERENCES public.ci_relationship_types (id),

    CONSTRAINT fk_ci_relationships_deactivated_by
        FOREIGN KEY (deactivated_by)
        REFERENCES public.users (id)
);


-- ============================================================================
-- 3. Indexes
-- ============================================================================

CREATE INDEX idx_ci_relationships_source_status
    ON public.ci_relationships (source_ci_id, status);

CREATE INDEX idx_ci_relationships_target_status
    ON public.ci_relationships (target_ci_id, status);

CREATE INDEX idx_ci_relationships_type
    ON public.ci_relationships (relationship_type_id);


