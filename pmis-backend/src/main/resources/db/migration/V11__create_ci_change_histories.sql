-- ============================================================================
-- V11: CMDB CI Change Histories
-- PostgreSQL
--
-- Purpose:
--   1. Store CI change event headers
--   2. Store before/after values for each changed attribute
--
-- Notes:
--   - before_data and after_data use JSONB.
--   - JSON null is stored as 'null'::jsonb, not SQL NULL.
--   - changed_by_name and change_summary are historical snapshots.
--   - History records are retained; no ON DELETE CASCADE is used.
-- ============================================================================


-- ============================================================================
-- 1. CI Change Histories
-- ============================================================================

CREATE TABLE public.ci_change_histories
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    ci_id               BIGINT NOT NULL,
    event_type          VARCHAR(30) NOT NULL,
    changed_by          BIGINT NOT NULL,
    changed_by_name     VARCHAR(100) NOT NULL,
    changed_at          TIMESTAMPTZ NOT NULL DEFAULT statement_timestamp(),
    change_summary      VARCHAR(500) NOT NULL,

    CONSTRAINT pk_ci_change_histories
        PRIMARY KEY (id),

    CONSTRAINT fk_ci_change_histories_ci
        FOREIGN KEY (ci_id)
        REFERENCES public.configuration_items (id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_ci_change_histories_changed_by
        FOREIGN KEY (changed_by)
        REFERENCES public.users (id)
        ON DELETE RESTRICT,

    CONSTRAINT ck_ci_change_histories_event_type
        CHECK (
            event_type IN (
                'CREATED',
                'UPDATED',
                'STATUS_CHANGED'
            )
        )
);


-- ============================================================================
-- 2. CI Change Details
-- ============================================================================

CREATE TABLE public.ci_change_details
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    history_id      BIGINT NOT NULL,
    attribute_key   VARCHAR(100) NOT NULL,
    before_data     JSONB NOT NULL,
    after_data      JSONB NOT NULL,

    CONSTRAINT pk_ci_change_details
        PRIMARY KEY (id),

    CONSTRAINT fk_ci_change_details_history
        FOREIGN KEY (history_id)
        REFERENCES public.ci_change_histories (id)
        ON DELETE RESTRICT,

    CONSTRAINT uk_ci_change_details_history_attribute
        UNIQUE (history_id, attribute_key)
);


-- ============================================================================
-- 3. Indexes
-- ============================================================================

-- CI별 변경 이력 최신순 조회
CREATE INDEX idx_ci_change_histories_ci_changed_at
    ON public.ci_change_histories (
        ci_id,
        changed_at DESC,
        id DESC
    );

-- CI별 이벤트 유형 필터 조회
CREATE INDEX idx_ci_change_histories_ci_event_changed_at
    ON public.ci_change_histories (
        ci_id,
        event_type,
        changed_at DESC,
        id DESC
    );

-- CI별 변경자 필터 조회
CREATE INDEX idx_ci_change_histories_ci_actor_changed_at
    ON public.ci_change_histories (
        ci_id,
        changed_by,
        changed_at DESC,
        id DESC
    );

-- 이력 상세 조회
CREATE INDEX idx_ci_change_details_history_id
    ON public.ci_change_details (history_id);


