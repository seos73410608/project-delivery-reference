-- ---------------------------------------------------------------------------
-- 5. System settings
-- setting_key is globally unique. Values are stored as text and interpreted
-- according to data_type by the application.
-- ---------------------------------------------------------------------------

CREATE TABLE public.system_settings (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    category_id bigint NOT NULL,
    setting_key character varying(100) NOT NULL,
    setting_value character varying(1000) NOT NULL,
    data_type character varying(20) NOT NULL,
    description character varying(500),
    editable boolean NOT NULL DEFAULT true,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone,
    CONSTRAINT system_settings_pkey PRIMARY KEY (id),
    CONSTRAINT uk_system_settings_setting_key UNIQUE (setting_key),
    CONSTRAINT ck_system_settings_data_type
        CHECK (data_type IN ('STRING', 'NUMBER', 'BOOLEAN', 'JSON')),
    CONSTRAINT fk_system_settings_category
        FOREIGN KEY (category_id)
        REFERENCES public.system_setting_categories(id)
);

CREATE INDEX idx_system_settings_category_id
    ON public.system_settings (category_id);

INSERT INTO public.system_settings (
    category_id,
    setting_key,
    setting_value,
    data_type,
    description,
    editable,
    created_at
)
SELECT
    c.id,
    'SESSION_HISTORY_RETENTION_DAYS',
    '365',
    'NUMBER',
    '세션 이력 보존 기간(일)',
    true,
    CURRENT_TIMESTAMP
FROM public.system_setting_categories c
WHERE c.category_key = 'DATA_RETENTION';

-- ---------------------------------------------------------------------------
-- 6. Remove legacy single-session refresh token storage
-- Existing refresh tokens are invalidated. Users must authenticate again.
-- ---------------------------------------------------------------------------

DROP TABLE public.refresh_tokens;
