-- V12: Multi-session authentication and system settings
-- PostgreSQL 18+
--
-- Important deployment note:
-- This migration removes the legacy refresh_tokens table. Existing refresh
-- tokens are intentionally invalidated because they do not contain sessionId
-- and cannot be safely migrated into user_sessions. Deploy this migration
-- together with the application version that uses user_sessions.
--
-- Existing users receive the default maximum of 5 concurrent sessions.
-- New users must receive a user_security_settings row in the user-creation
-- application flow (or a future database-level mechanism).

-- ---------------------------------------------------------------------------
-- 1. Per-user security settings
-- ---------------------------------------------------------------------------

CREATE TABLE public.user_security_settings (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id bigint NOT NULL,
    max_session_count integer NOT NULL DEFAULT 5,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone,
    CONSTRAINT user_security_settings_pkey PRIMARY KEY (id),
    CONSTRAINT uk_user_security_settings_user_id UNIQUE (user_id),
    CONSTRAINT ck_user_security_settings_max_session_count
        CHECK (max_session_count >= 1),
    CONSTRAINT fk_user_security_settings_user
        FOREIGN KEY (user_id) REFERENCES public.users(id)
);

INSERT INTO public.user_security_settings (
    user_id,
    max_session_count,
    created_at
)
SELECT
    u.id,
    5,
    CURRENT_TIMESTAMP
FROM public.users u;

-- ---------------------------------------------------------------------------
-- 2. Active user sessions
-- Only active sessions are stored here. Ended sessions are moved to
-- user_session_histories and deleted from this table in the same transaction.
-- ---------------------------------------------------------------------------

CREATE TABLE public.user_sessions (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    session_id uuid NOT NULL,
    user_id bigint NOT NULL,
    refresh_token_hash character varying(255) NOT NULL,
    refresh_token_expires_at timestamp(6) without time zone NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone,
    last_accessed_at timestamp(6) without time zone,
    CONSTRAINT user_sessions_pkey PRIMARY KEY (id),
    CONSTRAINT uk_user_sessions_session_id UNIQUE (session_id),
    CONSTRAINT fk_user_sessions_user
        FOREIGN KEY (user_id) REFERENCES public.users(id)
);

CREATE INDEX idx_user_sessions_user_id
    ON public.user_sessions (user_id);

CREATE INDEX idx_user_sessions_refresh_token_expires_at
    ON public.user_sessions (refresh_token_expires_at);

-- ---------------------------------------------------------------------------
-- 3. Ended session history
-- created_at preserves the original session creation time.
-- user_id intentionally retains a non-cascading FK to users.
-- ---------------------------------------------------------------------------

CREATE TABLE public.user_session_histories (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    session_id uuid NOT NULL,
    user_id bigint NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    last_accessed_at timestamp(6) without time zone,
    ended_at timestamp(6) without time zone NOT NULL,
    end_reason character varying(30) NOT NULL,
    CONSTRAINT user_session_histories_pkey PRIMARY KEY (id),
    CONSTRAINT uk_user_session_histories_session_id UNIQUE (session_id),
    CONSTRAINT ck_user_session_histories_end_reason
        CHECK (end_reason IN (
            'USER_LOGOUT',
            'USER_SELECTED',
            'ADMIN_REVOKED',
            'TOKEN_EXPIRED',
            'SECURITY_REVOKED'
        )),
    CONSTRAINT fk_user_session_histories_user
        FOREIGN KEY (user_id) REFERENCES public.users(id)
);

CREATE INDEX idx_user_session_histories_user_ended_at
    ON public.user_session_histories (user_id, ended_at DESC);

-- ---------------------------------------------------------------------------
-- 4. System setting categories
-- Only categories required by the current feature are seeded.
-- Future categories (e.g. DATA_ARCHIVE, SYSTEM_OPERATION) can be added
-- when their corresponding features are designed.
-- ---------------------------------------------------------------------------

CREATE TABLE public.system_setting_categories (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    category_key character varying(50) NOT NULL,
    category_name character varying(100) NOT NULL,
    description character varying(500),
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone,
    CONSTRAINT system_setting_categories_pkey PRIMARY KEY (id),
    CONSTRAINT uk_system_setting_categories_category_key UNIQUE (category_key)
);

INSERT INTO public.system_setting_categories (
