
-- V14: Operation domain
-- Enterprise-wide operation services and their participating companies
-- PostgreSQL 18+

-- ---------------------------------------------------------------------------
-- 1. Operations
-- Represents an enterprise-wide operational service or engagement.
-- It is independent from Project, Contract and OperationalScope.
-- ---------------------------------------------------------------------------

CREATE TABLE public.operations (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    operation_code character varying(50) NOT NULL,
    operation_name character varying(200) NOT NULL,
    operation_type character varying(30) NOT NULL,
    status character varying(20) NOT NULL DEFAULT 'PLANNED',
    manager_user_id bigint,
    description text,
    effective_from date,
    effective_to date,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone,
    CONSTRAINT operations_pkey PRIMARY KEY (id),
    CONSTRAINT uk_operations_operation_code UNIQUE (operation_code),
    CONSTRAINT fk_operations_manager
        FOREIGN KEY (manager_user_id) REFERENCES public.users(id),
    CONSTRAINT ck_operations_type
        CHECK (operation_type IN (
            'BUSINESS_SERVICE',
            'APPLICATION_SERVICE',
            'INFRASTRUCTURE_SERVICE',
            'PLATFORM_SERVICE',
            'DATABASE_SERVICE',
            'OTHER'
        )),
    CONSTRAINT ck_operations_status
        CHECK (status IN (
            'PLANNED',
            'ACTIVE',
            'SUSPENDED',
            'CLOSED'
        )),
    CONSTRAINT ck_operations_period
        CHECK (
            effective_to IS NULL
            OR (
                effective_from IS NOT NULL
                AND effective_from <= effective_to
            )
        )
);

CREATE INDEX idx_operations_type
    ON public.operations (operation_type);

CREATE INDEX idx_operations_status
    ON public.operations (status);

CREATE INDEX idx_operations_manager_user_id
    ON public.operations (manager_user_id);

CREATE INDEX idx_operations_period
    ON public.operations (effective_from, effective_to);


-- ---------------------------------------------------------------------------
-- 2. Operation participants
-- Companies and optional organizational units participating in operations.
-- The composite FK ensures that an organization belongs to the company.
-- Historical participation is preserved through effective dates.
-- ---------------------------------------------------------------------------

CREATE TABLE public.operation_participants (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    operation_id bigint NOT NULL,
    company_id bigint NOT NULL,
    organization_id bigint,
    participant_role character varying(30) NOT NULL,
    is_primary boolean NOT NULL DEFAULT false,
    effective_from date,
    effective_to date,
    description character varying(500),
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone,
    CONSTRAINT operation_participants_pkey PRIMARY KEY (id),
    CONSTRAINT fk_operation_participants_operation
        FOREIGN KEY (operation_id) REFERENCES public.operations(id),
    CONSTRAINT fk_operation_participants_company
        FOREIGN KEY (company_id) REFERENCES public.companies(id),
    CONSTRAINT fk_operation_participants_organization
        FOREIGN KEY (company_id, organization_id)
        REFERENCES public.organizations(company_id, id),
    CONSTRAINT ck_operation_participants_role
        CHECK (participant_role IN (
            'SERVICE_OWNER',
            'OPERATOR',
            'SERVICE_PROVIDER',
            'SUPPORT_PROVIDER',
            'CUSTOMER',
            'PARTNER'
        )),
    CONSTRAINT ck_operation_participants_period
        CHECK (
            effective_to IS NULL
            OR (
                effective_from IS NOT NULL
                AND effective_from <= effective_to
            )
        )
);

-- Prevent duplicate open-ended participation assignments.
-- NULLS NOT DISTINCT treats company-level participation
-- (organization_id IS NULL) as a comparable assignment.
CREATE UNIQUE INDEX uk_operation_participants_active_assignment
    ON public.operation_participants (
        operation_id,
        company_id,
        organization_id,
        participant_role
    )
    NULLS NOT DISTINCT
    WHERE effective_to IS NULL;

-- Allow only one open-ended primary participant per operation and role.
CREATE UNIQUE INDEX uk_operation_participants_primary_role
    ON public.operation_participants (
        operation_id,
        participant_role
    )
    WHERE is_primary = true
      AND effective_to IS NULL;

CREATE INDEX idx_operation_participants_operation_id
    ON public.operation_participants (operation_id);

CREATE INDEX idx_operation_participants_company_id
    ON public.operation_participants (company_id);

CREATE INDEX idx_operation_participants_organization_id
    ON public.operation_participants (organization_id);

CREATE INDEX idx_operation_participants_role
    ON public.operation_participants (participant_role);
