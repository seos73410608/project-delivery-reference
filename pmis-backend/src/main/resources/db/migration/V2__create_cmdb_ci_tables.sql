-- ============================================================================
-- 1. CI Type Code Sequence
-- ============================================================================
-- CI 업무 코드 생성용 Sequence
-- 형식: CI-000001, CI-000002, ...
-- 실제 ci_code 조합은 Service 계층에서 수행한다.

CREATE SEQUENCE public.configuration_item_code_seq
    AS BIGINT
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1;


-- ============================================================================
-- 2. CI Types
-- ============================================================================

CREATE TABLE public.ci_types
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    created_at  TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITHOUT TIME ZONE,

    code        VARCHAR(50) NOT NULL,
    name        VARCHAR(100) NOT NULL,
    parent_id   BIGINT,
    description TEXT,

    assignable BOOLEAN NOT NULL DEFAULT FALSE,
    enabled    BOOLEAN NOT NULL DEFAULT TRUE,
    sort_order  INTEGER NOT NULL DEFAULT 0,

    CONSTRAINT pk_ci_types
        PRIMARY KEY (id),

    CONSTRAINT uk_ci_types_code
        UNIQUE (code),

    CONSTRAINT fk_ci_types_parent
        FOREIGN KEY (parent_id)
        REFERENCES public.ci_types (id)
);


CREATE INDEX idx_ci_types_parent_id
    ON public.ci_types (parent_id);


-- ============================================================================
-- 3. Configuration Items
-- ============================================================================

CREATE TABLE public.configuration_items
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    created_at  TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITHOUT TIME ZONE,

    ci_code     VARCHAR(50) NOT NULL,
    ci_name     VARCHAR(200) NOT NULL,

    ci_type_id  BIGINT NOT NULL,
    status      VARCHAR(30) NOT NULL,
    environment VARCHAR(30),

    manager_id  BIGINT,
    location    VARCHAR(200),
    description TEXT,

    CONSTRAINT pk_configuration_items
        PRIMARY KEY (id),

    CONSTRAINT uk_configuration_items_ci_code
        UNIQUE (ci_code),

    CONSTRAINT fk_configuration_items_ci_type
        FOREIGN KEY (ci_type_id)
        REFERENCES public.ci_types (id),

    CONSTRAINT fk_configuration_items_manager
        FOREIGN KEY (manager_id)
        REFERENCES public.users (id)
);


CREATE INDEX idx_configuration_items_ci_type_id
    ON public.configuration_items (ci_type_id);

CREATE INDEX idx_configuration_items_manager_id
    ON public.configuration_items (manager_id);


