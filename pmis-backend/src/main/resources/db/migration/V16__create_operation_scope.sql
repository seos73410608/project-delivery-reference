
-- V16: Operation-OperationalScope relationship domain
-- Connects enterprise operations with operational scopes.
-- Historical relationships are retained when a new relationship is created.
-- PostgreSQL 18+

-- ---------------------------------------------------------------------------
-- 1. Operation-OperationalScope relationships
-- An operation can be linked to multiple operational scopes, and an
-- operational scope can be linked to multiple operations.
-- ---------------------------------------------------------------------------

CREATE TABLE public.operation_scopes (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    operation_id bigint NOT NULL,
    operational_scope_id bigint NOT NULL,
    status character varying(20) NOT NULL DEFAULT 'PLANNED',
    effective_from date,
    effective_to date,
    description text,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone,

    CONSTRAINT operation_scopes_pkey
        PRIMARY KEY (id),

    CONSTRAINT fk_operation_scopes_operation
        FOREIGN KEY (operation_id)
        REFERENCES public.operations(id),

    CONSTRAINT fk_operation_scopes_operational_scope
        FOREIGN KEY (operational_scope_id)
        REFERENCES public.operational_scopes(id),

    CONSTRAINT ck_operation_scopes_status
        CHECK (status IN (
            'PLANNED',
            'ACTIVE',
            'COMPLETED',
            'CANCELLED'
        )),

    CONSTRAINT ck_operation_scopes_period
        CHECK (
            effective_to IS NULL
            OR (
                effective_from IS NOT NULL
                AND effective_from <= effective_to
            )
        )
);

-- Prevent duplicate active relationships for the same operation and scope.
-- Historical COMPLETED and CANCELLED relationships are retained.
CREATE UNIQUE INDEX uk_operation_scopes_active_relationship
    ON public.operation_scopes (operation_id, operational_scope_id)
    WHERE status IN ('PLANNED', 'ACTIVE');

CREATE INDEX idx_operation_scopes_operation_id
    ON public.operation_scopes (operation_id);

CREATE INDEX idx_operation_scopes_operational_scope_id
    ON public.operation_scopes (operational_scope_id);

CREATE INDEX idx_operation_scopes_status
    ON public.operation_scopes (status);
