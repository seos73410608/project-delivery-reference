
-- V15: Project-Operation relationship and handover domain
-- Supports initial handover, operator changes and re-handovers.
-- PostgreSQL 18+

-- ---------------------------------------------------------------------------
-- 1. Composite candidate key for operation participants
-- Enables handover participant references to enforce operation ownership.
-- ---------------------------------------------------------------------------

CREATE UNIQUE INDEX uk_operation_participants_operation_id_id
    ON public.operation_participants (operation_id, id);


-- ---------------------------------------------------------------------------
-- 2. Project-Operation relationships
-- A project can produce multiple operations, and an operation can be
-- associated with multiple projects.
-- ---------------------------------------------------------------------------

CREATE TABLE public.project_operations (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    project_id bigint NOT NULL,
    operation_id bigint NOT NULL,
    relationship_type character varying(30) NOT NULL,
    status character varying(20) NOT NULL DEFAULT 'PLANNED',
    effective_from date,
    effective_to date,
    description text,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone,

    CONSTRAINT project_operations_pkey
        PRIMARY KEY (id),

    CONSTRAINT uk_project_operations_id_operation_id
        UNIQUE (id, operation_id),

    CONSTRAINT fk_project_operations_project
        FOREIGN KEY (project_id)
        REFERENCES public.projects(id),

    CONSTRAINT fk_project_operations_operation
        FOREIGN KEY (operation_id)
        REFERENCES public.operations(id),

    CONSTRAINT ck_project_operations_relationship_type
        CHECK (relationship_type IN (
            'BUILD_RESULT',
            'ENHANCEMENT',
            'MIGRATION',
            'OTHER'
        )),

    CONSTRAINT ck_project_operations_status
        CHECK (status IN (
            'PLANNED',
            'ACTIVE',
            'COMPLETED',
            'CANCELLED'
        )),

    CONSTRAINT ck_project_operations_period
        CHECK (
            effective_to IS NULL
            OR (
                effective_from IS NOT NULL
                AND effective_from <= effective_to
            )
        )
);

-- Prevent duplicate active relationships for the same project and operation.
CREATE UNIQUE INDEX uk_project_operations_active_relationship
    ON public.project_operations (project_id, operation_id)
    WHERE status IN ('PLANNED', 'ACTIVE');

CREATE INDEX idx_project_operations_project_id
    ON public.project_operations (project_id);

CREATE INDEX idx_project_operations_operation_id
    ON public.project_operations (operation_id);

CREATE INDEX idx_project_operations_status
    ON public.project_operations (status);


-- ---------------------------------------------------------------------------
-- 3. Project-Operation handover history
-- Each handover is an independent event.
-- Previous handovers are retained and linked through previous_handover_id.
-- ---------------------------------------------------------------------------

CREATE TABLE public.project_operation_handovers (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    project_operation_id bigint NOT NULL,
    operation_id bigint NOT NULL,
    handover_type character varying(30) NOT NULL,
    status character varying(20) NOT NULL DEFAULT 'DRAFT',
    sequence_no integer NOT NULL,
    previous_handover_id bigint,
    from_participant_id bigint,
    to_participant_id bigint NOT NULL,
    handed_over_by_user_id bigint,
    accepted_by_user_id bigint,
    planned_handover_date date,
    requested_at timestamp(6) without time zone,
    accepted_at timestamp(6) without time zone,
    completed_at timestamp(6) without time zone,
    notes text,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone,

    CONSTRAINT project_operation_handovers_pkey
        PRIMARY KEY (id),

    CONSTRAINT uk_project_operation_handovers_id_operation_id
        UNIQUE (id, operation_id),

    CONSTRAINT uk_project_operation_handovers_id_project_operation_operation
        UNIQUE (id, project_operation_id, operation_id),

    CONSTRAINT uk_project_operation_handovers_sequence
        UNIQUE (project_operation_id, sequence_no),

    CONSTRAINT fk_project_operation_handovers_project_operation
        FOREIGN KEY (project_operation_id, operation_id)
        REFERENCES public.project_operations(id, operation_id),

    CONSTRAINT fk_project_operation_handovers_previous
        FOREIGN KEY (
            previous_handover_id,
            project_operation_id,
            operation_id
        )
        REFERENCES public.project_operation_handovers (
            id,
            project_operation_id,
            operation_id
        ),

    CONSTRAINT fk_project_operation_handovers_from_participant
        FOREIGN KEY (operation_id, from_participant_id)
        REFERENCES public.operation_participants(operation_id, id),

    CONSTRAINT fk_project_operation_handovers_to_participant
        FOREIGN KEY (operation_id, to_participant_id)
        REFERENCES public.operation_participants(operation_id, id),

    CONSTRAINT fk_project_operation_handovers_handed_over_by
        FOREIGN KEY (handed_over_by_user_id)
        REFERENCES public.users(id),

    CONSTRAINT fk_project_operation_handovers_accepted_by
        FOREIGN KEY (accepted_by_user_id)
        REFERENCES public.users(id),

    CONSTRAINT ck_project_operation_handovers_type
        CHECK (handover_type IN (
            'INITIAL',
            'OPERATOR_CHANGE',
            'RE_HANDOVER'
        )),

    CONSTRAINT ck_project_operation_handovers_status
        CHECK (status IN (
            'DRAFT',
            'REQUESTED',
            'IN_PROGRESS',
            'REVIEW',
            'ACCEPTED',
            'COMPLETED',
            'REJECTED',
            'CANCELLED'
        )),

    CONSTRAINT ck_project_operation_handovers_sequence
        CHECK (sequence_no > 0),

    CONSTRAINT ck_project_operation_handovers_participants
        CHECK (
            from_participant_id IS NULL
            OR from_participant_id <> to_participant_id
        ),

    CONSTRAINT ck_project_operation_handovers_initial
        CHECK (
            handover_type <> 'INITIAL'
            OR from_participant_id IS NULL
        ),

    CONSTRAINT ck_project_operation_handovers_non_initial
        CHECK (
            handover_type = 'INITIAL'
            OR from_participant_id IS NOT NULL
        ),

    CONSTRAINT ck_project_operation_handovers_not_self_previous
        CHECK (
            previous_handover_id IS NULL
            OR previous_handover_id <> id
        ),

    CONSTRAINT ck_project_operation_handovers_accepted
        CHECK (
            status NOT IN ('ACCEPTED', 'COMPLETED')
            OR (
                accepted_by_user_id IS NOT NULL
                AND accepted_at IS NOT NULL
            )
        ),

    CONSTRAINT ck_project_operation_handovers_completed
        CHECK (
            status <> 'COMPLETED'
            OR completed_at IS NOT NULL
        ),

    CONSTRAINT ck_project_operation_handovers_requested
        CHECK (
            requested_at IS NULL
            OR requested_at >= created_at
        ),

    CONSTRAINT ck_project_operation_handovers_dates
        CHECK (
            accepted_at IS NULL
            OR (
                requested_at IS NOT NULL
                AND accepted_at >= requested_at
            )
        ),

    CONSTRAINT ck_project_operation_handovers_completion_date
        CHECK (
            completed_at IS NULL
            OR (
                accepted_at IS NOT NULL
                AND completed_at >= accepted_at
            )
        )
);

-- One currently active handover process per project-operation relationship.
CREATE UNIQUE INDEX uk_project_operation_handovers_active
    ON public.project_operation_handovers (project_operation_id)
    WHERE status IN (
        'REQUESTED',
        'IN_PROGRESS',
        'REVIEW',
        'ACCEPTED'
    );

CREATE INDEX idx_project_operation_handovers_project_operation_id
    ON public.project_operation_handovers (project_operation_id);

CREATE INDEX idx_project_operation_handovers_operation_id
    ON public.project_operation_handovers (operation_id);

CREATE INDEX idx_project_operation_handovers_status
    ON public.project_operation_handovers (status);

CREATE INDEX idx_project_operation_handovers_from_participant
    ON public.project_operation_handovers (from_participant_id);

CREATE INDEX idx_project_operation_handovers_to_participant
    ON public.project_operation_handovers (to_participant_id);

CREATE INDEX idx_project_operation_handovers_previous
    ON public.project_operation_handovers (previous_handover_id);
