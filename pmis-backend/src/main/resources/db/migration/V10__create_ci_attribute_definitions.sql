-- ============================================================================
-- 1. CI Attribute Definitions
-- ============================================================================

CREATE TABLE public.ci_attribute_definitions
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    created_at      TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP WITHOUT TIME ZONE,

    parent_id       BIGINT,
    ci_type_id      BIGINT,

    attribute_key   VARCHAR(100) NOT NULL,
    display_name    VARCHAR(100) NOT NULL,

    node_type       VARCHAR(20) NOT NULL,
    data_type       VARCHAR(20),
    reference_type  VARCHAR(50),

    display_format  VARCHAR(100),
    display_order   INTEGER NOT NULL DEFAULT 0,

    enabled         BOOLEAN NOT NULL DEFAULT TRUE,
    description     TEXT,

    CONSTRAINT pk_ci_attribute_definitions
        PRIMARY KEY (id),

    CONSTRAINT uk_ci_attribute_definitions_attribute_key
        UNIQUE (attribute_key),

    CONSTRAINT fk_ci_attribute_definitions_parent
        FOREIGN KEY (parent_id)
        REFERENCES public.ci_attribute_definitions (id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_ci_attribute_definitions_ci_type
        FOREIGN KEY (ci_type_id)
        REFERENCES public.ci_types (id)
        ON DELETE RESTRICT,

    CONSTRAINT ck_ci_attribute_definitions_node_type
        CHECK (node_type IN ('GROUP', 'FIELD')),

    CONSTRAINT ck_ci_attribute_definitions_data_type
        CHECK (
            (
                node_type = 'GROUP'
                AND data_type IS NULL
                AND reference_type IS NULL
            )
            OR
            (
                node_type = 'FIELD'
                AND data_type IS NOT NULL
                AND data_type IN (
                    'STRING',
                    'NUMBER',
                    'BOOLEAN',
                    'DATE',
                    'DATETIME',
                    'OBJECT',
                    'ARRAY',
                    'REFERENCE'
                )
                AND (
                    (data_type = 'REFERENCE' AND reference_type IS NOT NULL)
                    OR
                    (data_type <> 'REFERENCE' AND reference_type IS NULL)
                )
            )
        ),

    CONSTRAINT ck_ci_attribute_definitions_not_self_parent
        CHECK (
            parent_id IS NULL
            OR parent_id <> id
        )
);


-- ============================================================================
-- 2. Indexes
-- ============================================================================

CREATE INDEX idx_ci_attribute_definitions_parent_id
    ON public.ci_attribute_definitions (parent_id);

CREATE INDEX idx_ci_attribute_definitions_ci_type_id
    ON public.ci_attribute_definitions (ci_type_id);

CREATE INDEX idx_ci_attribute_definitions_type_enabled_order
    ON public.ci_attribute_definitions (
        ci_type_id,
        enabled,
        display_order
    );


