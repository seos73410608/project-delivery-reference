CREATE TABLE public.server_details
(
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    created_at              TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at              TIMESTAMP WITHOUT TIME ZONE,

    ci_id                   BIGINT NOT NULL,
    hostname                VARCHAR(200) NOT NULL,
    server_category         VARCHAR(30) NOT NULL,

    management_ip           VARCHAR(100),
    os_name                 VARCHAR(100),
    os_version              VARCHAR(100),
    cpu_cores               INTEGER,
    memory_size_mb          BIGINT,
    virtualization_platform VARCHAR(100),

    CONSTRAINT pk_server_details
        PRIMARY KEY (id),

    CONSTRAINT uk_server_details_ci_id
        UNIQUE (ci_id),

    CONSTRAINT fk_server_details_ci
        FOREIGN KEY (ci_id)
        REFERENCES public.configuration_items (id),

    CONSTRAINT ck_server_details_category
        CHECK (server_category IN ('PHYSICAL', 'VIRTUAL')),

    CONSTRAINT ck_server_details_cpu_cores
        CHECK (cpu_cores IS NULL OR cpu_cores > 0),

    CONSTRAINT ck_server_details_memory_size_mb
        CHECK (memory_size_mb IS NULL OR memory_size_mb > 0)
);

