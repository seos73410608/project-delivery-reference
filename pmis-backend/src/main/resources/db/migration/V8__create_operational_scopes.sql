-- =========================================================================
-- V8: Create Operational Scope
-- =========================================================================
-- Operational Scope is an independent logical operational boundary.
-- It is not a Project and is not a Configuration Item.
--
-- Sequence:
--   1. operational_scope_code_seq
--
-- Table:
--   1. operational_scopes
-- =========================================================================


-- =========================================================================
-- 1. Operational Scope Code Sequence
-- =========================================================================

CREATE SEQUENCE public.operational_scope_code_seq
    AS BIGINT
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1;


-- =========================================================================
-- 2. Operational Scopes
-- =========================================================================

CREATE TABLE public.operational_scopes
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    created_at      TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at      TIMESTAMP WITHOUT TIME ZONE,

    scope_code      VARCHAR(50) NOT NULL,
    scope_name      VARCHAR(200) NOT NULL,
    scope_type      VARCHAR(30) NOT NULL,
    status          VARCHAR(30) NOT NULL DEFAULT 'PLANNED',

    parent_scope_id BIGINT,
    owner_user_id   BIGINT,

    description     TEXT,

    effective_from  DATE,
    effective_to    DATE,

    version         BIGINT NOT NULL DEFAULT 0,

    CONSTRAINT pk_operational_scopes
        PRIMARY KEY (id),

    CONSTRAINT uk_operational_scopes_scope_code
        UNIQUE (scope_code),

    CONSTRAINT fk_operational_scopes_parent
        FOREIGN KEY (parent_scope_id)
        REFERENCES public.operational_scopes (id),

    CONSTRAINT fk_operational_scopes_owner
        FOREIGN KEY (owner_user_id)
        REFERENCES public.users (id),

    CONSTRAINT ck_operational_scopes_scope_type
        CHECK (
            scope_type IN (
                'SERVICE',
                'SYSTEM',
                'ENVIRONMENT',
                'PLATFORM',
                'DATABASE',
                'SERVER_GROUP',
                'CI_SCOPE'
            )
        ),

    CONSTRAINT ck_operational_scopes_status
        CHECK (
            status IN (
                'PLANNED',
                'ACTIVE',
                'SUSPENDED',
                'CLOSED'
            )
        ),

    CONSTRAINT ck_operational_scopes_effective_period
        CHECK (
            effective_to IS NULL
            OR (
                effective_from IS NOT NULL
                AND effective_from <= effective_to
            )
        ),

    CONSTRAINT ck_operational_scopes_not_self_parent
        CHECK (
            parent_scope_id IS NULL
            OR parent_scope_id <> id
        )
);


-- =========================================================================
-- 3. Indexes
-- =========================================================================

CREATE INDEX idx_operational_scopes_parent_scope_id
    ON public.operational_scopes (parent_scope_id);

CREATE INDEX idx_operational_scopes_owner_user_id
    ON public.operational_scopes (owner_user_id);

CREATE INDEX idx_operational_scopes_scope_type_status
    ON public.operational_scopes (scope_type, status);


