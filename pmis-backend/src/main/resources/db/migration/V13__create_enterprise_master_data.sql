
-- V13: Enterprise master data
-- Enterprise-wide companies, organizations, user assignments and contracts
-- PostgreSQL 18+

-- ---------------------------------------------------------------------------
-- 1. Companies
-- A company represents a legal or business entity.
-- Its business roles are managed separately because one company may have
-- multiple roles (e.g. customer and partner).
-- ---------------------------------------------------------------------------

CREATE TABLE public.companies (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    company_code character varying(50) NOT NULL,
    company_name character varying(200) NOT NULL,
    legal_name character varying(250),
    business_registration_number character varying(30),
    country_code character varying(2) NOT NULL DEFAULT 'KR',
    website character varying(500),
    status character varying(20) NOT NULL DEFAULT 'ACTIVE',
    description text,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone,
    CONSTRAINT companies_pkey PRIMARY KEY (id),
    CONSTRAINT uk_companies_company_code UNIQUE (company_code),
    CONSTRAINT ck_companies_status
        CHECK (status IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT ck_companies_country_code
        CHECK (country_code ~ '^[A-Z]{2}$')
);

CREATE UNIQUE INDEX uk_companies_business_registration_number
    ON public.companies (business_registration_number)
    WHERE business_registration_number IS NOT NULL;

CREATE INDEX idx_companies_company_name
    ON public.companies (company_name);

CREATE INDEX idx_companies_status
    ON public.companies (status);


