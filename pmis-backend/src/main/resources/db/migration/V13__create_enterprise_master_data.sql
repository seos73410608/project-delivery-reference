-- ---------------------------------------------------------------------------
-- 3. Company role assignments
-- Historical company-role assignments are preserved.
-- Only one open-ended assignment per company and role is allowed.
-- ---------------------------------------------------------------------------

CREATE TABLE public.company_role_assignments (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    company_id bigint NOT NULL,
    company_role_id bigint NOT NULL,
    effective_from date NOT NULL,
    effective_to date,
    description character varying(500),
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone,
    CONSTRAINT company_role_assignments_pkey PRIMARY KEY (id),
    CONSTRAINT fk_company_role_assignments_company
        FOREIGN KEY (company_id) REFERENCES public.companies(id),
    CONSTRAINT fk_company_role_assignments_role
        FOREIGN KEY (company_role_id) REFERENCES public.company_roles(id),
    CONSTRAINT ck_company_role_assignments_period
        CHECK (effective_to IS NULL OR effective_from <= effective_to)
);

CREATE UNIQUE INDEX uk_company_role_assignments_active
    ON public.company_role_assignments (company_id, company_role_id)
    WHERE effective_to IS NULL;

CREATE INDEX idx_company_role_assignments_company_id
    ON public.company_role_assignments (company_id);

CREATE INDEX idx_company_role_assignments_role_id
    ON public.company_role_assignments (company_role_id);


-- ---------------------------------------------------------------------------
-- 4. Organizations
-- Hierarchical organizational units belonging to a company.
-- The composite parent FK ensures parent and child belong to the same company.
-- ---------------------------------------------------------------------------

CREATE TABLE public.organizations (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    company_id bigint NOT NULL,
    parent_organization_id bigint,
    organization_code character varying(50) NOT NULL,
    organization_name character varying(200) NOT NULL,
    organization_type character varying(30) NOT NULL,
    manager_user_id bigint,
    status character varying(20) NOT NULL DEFAULT 'ACTIVE',
    effective_from date,
    effective_to date,
    description text,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone,
    CONSTRAINT organizations_pkey PRIMARY KEY (id),
    CONSTRAINT uk_organizations_company_code
        UNIQUE (company_id, organization_code),
    CONSTRAINT uk_organizations_company_id_id
        UNIQUE (company_id, id),
    CONSTRAINT fk_organizations_company
        FOREIGN KEY (company_id) REFERENCES public.companies(id),
    CONSTRAINT fk_organizations_parent
        FOREIGN KEY (company_id, parent_organization_id)
        REFERENCES public.organizations(company_id, id),
    CONSTRAINT fk_organizations_manager
        FOREIGN KEY (manager_user_id) REFERENCES public.users(id),
    CONSTRAINT ck_organizations_type
        CHECK (organization_type IN (
            'HEADQUARTERS',
            'DIVISION',
            'DEPARTMENT',
            'TEAM',
            'BRANCH',
            'CENTER',
            'OTHER'
        )),
    CONSTRAINT ck_organizations_status
        CHECK (status IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT ck_organizations_not_self_parent
        CHECK (
            parent_organization_id IS NULL
            OR parent_organization_id <> id
        ),
    CONSTRAINT ck_organizations_period
        CHECK (
            effective_to IS NULL
            OR (
                effective_from IS NOT NULL
                AND effective_from <= effective_to
            )
        )
);

CREATE INDEX idx_organizations_company_id
    ON public.organizations (company_id);

CREATE INDEX idx_organizations_parent_id
    ON public.organizations (parent_organization_id);

CREATE INDEX idx_organizations_manager_user_id
    ON public.organizations (manager_user_id);

CREATE INDEX idx_organizations_status
    ON public.organizations (company_id, status);


-- ---------------------------------------------------------------------------
-- 5. User organization assignments
-- Users may have primary, secondary, dispatched or temporary assignments.
-- Assignment history is retained independently from system access roles.
-- ---------------------------------------------------------------------------

CREATE TABLE public.user_organization_assignments (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id bigint NOT NULL,
    organization_id bigint NOT NULL,
    assignment_type character varying(30) NOT NULL,
    is_primary boolean NOT NULL DEFAULT false,
    effective_from date NOT NULL,
    effective_to date,
    description character varying(500),
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone,
    CONSTRAINT user_organization_assignments_pkey PRIMARY KEY (id),
    CONSTRAINT fk_user_organization_assignments_user
        FOREIGN KEY (user_id) REFERENCES public.users(id),
    CONSTRAINT fk_user_organization_assignments_organization
        FOREIGN KEY (organization_id) REFERENCES public.organizations(id),
    CONSTRAINT ck_user_organization_assignments_type
        CHECK (assignment_type IN (
            'PRIMARY',
            'SECONDARY',
            'DISPATCHED',
            'TEMPORARY'
        )),
    CONSTRAINT ck_user_organization_assignments_period
        CHECK (effective_to IS NULL OR effective_from <= effective_to),
    CONSTRAINT ck_user_organization_assignments_primary
        CHECK (NOT is_primary OR assignment_type = 'PRIMARY')
);

CREATE INDEX idx_user_organization_assignments_user_id
    ON public.user_organization_assignments (user_id);

CREATE INDEX idx_user_organization_assignments_organization_id
    ON public.user_organization_assignments (organization_id);

CREATE INDEX idx_user_organization_assignments_period
    ON public.user_organization_assignments (user_id, effective_from, effective_to);

CREATE UNIQUE INDEX uk_user_organization_assignments_open_primary
    ON public.user_organization_assignments (user_id)
    WHERE is_primary = true AND effective_to IS NULL;


-- ---------------------------------------------------------------------------
-- 6. Contracts
-- Contract master data.
-- Contract parties are managed separately to support multiple participants.
-- ---------------------------------------------------------------------------

CREATE TABLE public.contracts (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    contract_code character varying(50) NOT NULL,
    contract_name character varying(200) NOT NULL,
    contract_type character varying(30) NOT NULL,
    status character varying(20) NOT NULL DEFAULT 'DRAFT',
    signed_date date,
    start_date date NOT NULL,
    end_date date NOT NULL,
    currency_code character varying(3) NOT NULL DEFAULT 'KRW',
    contract_amount numeric(19, 4),
    description text,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone,
    CONSTRAINT contracts_pkey PRIMARY KEY (id),
    CONSTRAINT uk_contracts_contract_code UNIQUE (contract_code),
    CONSTRAINT ck_contracts_type
        CHECK (contract_type IN (
            'PROJECT',
            'MAINTENANCE',
            'OPERATION',
            'SUPPLY',
            'SERVICE',
            'OTHER'
        )),
    CONSTRAINT ck_contracts_status
        CHECK (status IN (
            'DRAFT',
            'ACTIVE',
            'SUSPENDED',
            'COMPLETED',
            'EXPIRED',
            'TERMINATED'
        )),
    CONSTRAINT ck_contracts_period
        CHECK (start_date <= end_date),
    CONSTRAINT ck_contracts_amount
        CHECK (contract_amount IS NULL OR contract_amount >= 0),
    CONSTRAINT ck_contracts_currency_code
        CHECK (currency_code ~ '^[A-Z]{3}$')
);

CREATE INDEX idx_contracts_status
    ON public.contracts (status);

CREATE INDEX idx_contracts_period
    ON public.contracts (start_date, end_date);

CREATE INDEX idx_contracts_contract_type
    ON public.contracts (contract_type);


-- ---------------------------------------------------------------------------
-- 7. Contract parties
-- Multiple companies and optional organizational units may participate
-- in a contract. The composite FK ensures organization belongs to company.
-- ---------------------------------------------------------------------------

CREATE TABLE public.contract_parties (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    contract_id bigint NOT NULL,
    company_id bigint NOT NULL,
    organization_id bigint,
    party_role character varying(30) NOT NULL,
    is_primary boolean NOT NULL DEFAULT false,
    effective_from date,
    effective_to date,
    description character varying(500),
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone,
    CONSTRAINT contract_parties_pkey PRIMARY KEY (id),
    CONSTRAINT fk_contract_parties_contract
        FOREIGN KEY (contract_id) REFERENCES public.contracts(id),
    CONSTRAINT fk_contract_parties_company
        FOREIGN KEY (company_id) REFERENCES public.companies(id),
    CONSTRAINT fk_contract_parties_organization
        FOREIGN KEY (company_id, organization_id)
        REFERENCES public.organizations(company_id, id),
    CONSTRAINT ck_contract_parties_role
        CHECK (party_role IN (
            'CLIENT',
            'CONTRACTOR',
            'SUBCONTRACTOR',
            'SUPPLIER',
            'PARTNER'
        )),
    CONSTRAINT ck_contract_parties_period
        CHECK (
            effective_to IS NULL
            OR (
                effective_from IS NOT NULL
                AND effective_from <= effective_to
            )
        )
);

CREATE UNIQUE INDEX uk_contract_parties_active_assignment
    ON public.contract_parties (
        contract_id,
        company_id,
        organization_id,
        party_role
    )
    NULLS NOT DISTINCT
    WHERE effective_to IS NULL;

CREATE INDEX idx_contract_parties_contract_id
    ON public.contract_parties (contract_id);

CREATE INDEX idx_contract_parties_company_id
    ON public.contract_parties (company_id);

CREATE INDEX idx_contract_parties_organization_id
    ON public.contract_parties (organization_id);

CREATE INDEX idx_contract_parties_role
    ON public.contract_parties (party_role);
